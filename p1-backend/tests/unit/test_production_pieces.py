"""Production building blocks that need no external service: Qdrant collection isolation (embedded Qdrant), Qdrant
JWT access tokens, SQL translation for PostgreSQL, request hardening middleware and the production config guard."""
import jwt
import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from app.rag.qdrant_store import QdrantStore
from app.rag.qdrant_tokens import claims_for, mint
from app.rag.vector_store import HashingEmbedder
from app.sim.pgdb import to_pg, translate_schema

TEXTS = {
    1: ("manual", None, "pump", "Pump manual: replace the mechanical seal when it leaks"),
    2: ("manual", None, "cnc", "CNC manual: spindle bearing preload and vibration limits"),
    10: ("work_order", "PLANT-A", "cnc", "Plant A repair: spindle bearing replaced after vibration rose"),
    20: ("work_order", "PLANT-B", "cnc", "Plant B repair: spindle bearing replaced, vibration back to normal"),
}


@pytest.fixture()
def store():
    from qdrant_client import QdrantClient
    emb = HashingEmbedder(dim=256).fit([t for *_, t in TEXTS.values()])
    s = QdrantStore(QdrantClient(":memory:"), emb, prefix="t")
    s.ensure(["PLANT-A", "PLANT-B"])
    for cid, (kind, plant, atype, text) in TEXTS.items():
        coll = s.workorders(plant) if kind == "work_order" else s.manuals()
        s.add(coll, [(cid, text, {"doc_id": str(cid), "kind": kind, "asset_type": atype, "plant_id": plant})])
    return s


def test_collections_are_named_per_environment_and_plant(store):
    assert store.manuals() == "t_manuals"
    assert store.workorders("PLANT-A") == "t_workorders_plant_a"
    assert store.size([store.manuals()]) == 2 and store.size([store.workorders("PLANT-B")]) == 1


def test_search_only_opens_the_given_collections(store):
    only_a = store.search("spindle bearing vibration", 10, [store.manuals(), store.workorders("PLANT-A")])
    ids = {i for i, _, _ in only_a}
    assert 10 in ids and 20 not in ids
    both = {i for i, _, _ in store.search("spindle bearing vibration", 10,
                                          [store.workorders("PLANT-A"), store.workorders("PLANT-B")])}
    assert {10, 20} <= both


def test_search_filters_by_machine_type(store):
    hits = store.search("replace", 10, [store.manuals()], asset_type="pump")
    assert [i for i, _, _ in hits] == [1]


def test_reindexing_a_chunk_replaces_it(store):
    store.delete(store.workorders("PLANT-A"), [10])
    store.add(store.workorders("PLANT-A"), [(11, "Plant A repair: coupling realigned", {"kind": "work_order"})])
    assert {i for i, _, _ in store.search("repair", 10, [store.workorders("PLANT-A")])} == {11}


def test_qdrant_tokens_name_exact_collections():
    c = claims_for("plant", "plantguard_prod", ["PLANT-A"], 30)
    assert c["access"] == [{"collection": "plantguard_prod_manuals", "access": "r"},
                           {"collection": "plantguard_prod_workorders_plant_a", "access": "rw"}]
    ro = claims_for("readonly", "p", ["PLANT-A", "PLANT-B"], 0)
    assert all(a["access"] == "r" for a in ro["access"]) and "exp" not in ro
    with pytest.raises(ValueError):
        claims_for("plant", "p", ["PLANT-A", "PLANT-B"], 1)
    tok = mint("k" * 32, "app", "p", ["PLANT-A"], 1)
    assert jwt.decode(tok, "k" * 32, algorithms=["HS256"])["sub"] == "plantguard-app"


def test_sql_translation_for_postgres():
    assert to_pg("SELECT * FROM t WHERE a=? AND b LIKE 'x%?'") == "SELECT * FROM t WHERE a=%s AND b LIKE 'x%%?'"
    stmts = translate_schema("CREATE TABLE IF NOT EXISTS child (id INTEGER PRIMARY KEY, p TEXT REFERENCES parent(id), "
                             "v REAL);\nCREATE TABLE IF NOT EXISTS parent (id TEXT PRIMARY KEY);\n"
                             "CREATE INDEX IF NOT EXISTS ix ON child(p);")
    assert stmts[0].startswith("CREATE TABLE IF NOT EXISTS parent")  # foreign-key order
    assert "GENERATED BY DEFAULT AS IDENTITY" in stmts[1] and "DOUBLE PRECISION" in stmts[1]
    assert stmts[2].startswith("CREATE INDEX")


def test_request_middleware_adds_security_headers_and_request_id():
    from app.core.observability import RequestContextMiddleware
    app = FastAPI()

    @app.get("/x")
    def x():
        return {"ok": True}
    app.add_middleware(RequestContextMiddleware, hsts=True)
    r = TestClient(app).get("/x", headers={"X-Request-ID": "abc"})
    assert r.headers["x-request-id"] == "abc"
    assert r.headers["x-content-type-options"] == "nosniff" and r.headers["x-frame-options"] == "DENY"
    assert "max-age" in r.headers["strict-transport-security"] and r.headers["cache-control"] == "no-store"
    assert len(TestClient(app).get("/x").headers["x-request-id"]) == 32


def test_json_log_lines_carry_severity_and_trace(monkeypatch):
    import json
    import logging
    from app.core.observability import JsonFormatter, _trace
    t = _trace.set("abc123")
    try:
        rec = logging.LogRecord("plantguard", logging.WARNING, __file__, 1, "hello %s", ("world",), None)
        out = json.loads(JsonFormatter("proj").format(rec))
    finally:
        _trace.reset(t)
    assert out["severity"] == "WARNING" and out["message"] == "hello world"
    assert out["logging.googleapis.com/trace"] == "projects/proj/traces/abc123"


def test_production_refuses_demo_settings(monkeypatch):
    from types import SimpleNamespace
    from app.main import check_production_config
    monkeypatch.setenv("PLANTGUARD_ENV", "prod")
    verifier = SimpleNamespace(secret="demo-secret-change-me", config=lambda: SimpleNamespace(mode="local"))
    c = SimpleNamespace(verifier=verifier, settings=SimpleNamespace(cors_origins=("*",)), role="api")
    with pytest.raises(RuntimeError) as e:
        check_production_config(c)
    assert "JWT_SECRET" in str(e.value) and "CORS_ORIGINS" in str(e.value)
    c.verifier = SimpleNamespace(secret="x" * 40, config=lambda: SimpleNamespace(mode="keycloak"))
    c.settings = SimpleNamespace(cors_origins=("https://plantguard.example.com",))
    check_production_config(c)  # fine
