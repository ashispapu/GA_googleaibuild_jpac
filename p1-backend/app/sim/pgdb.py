"""PostgreSQL implementation of the plant databases (production: Cloud SQL for PostgreSQL).

Same interface as the SQLite `Database` (q / one / val / x / many / tx / meta / next_id), so every service and
connector runs unchanged on either store. The OT and IT stores stay two separate databases (two DSNs), exactly as on
SQLite and as in a real plant.

What this class takes care of:
  - a thread-safe connection pool (psycopg 3); every call borrows a connection, transactions keep one;
  - `?` placeholders -> `%s`; rows that behave like sqlite3.Row (row["col"] and row[0]);
  - NUMERIC results (AVG/SUM of integers) come back as float, like SQLite;
  - the shared schema text is translated (AUTOINCREMENT -> identity, REAL -> double precision) and the tables are
    created in foreign-key order (SQLite accepts forward references, Postgres does not);
  - id sequences are atomic across processes (UPDATE ... RETURNING), so several API / worker instances never hand
    out the same INC-/WO-/STO- number;
  - `advisory_lock(key)` serialises writers that must be strictly ordered (the audit hash chain).
"""
from __future__ import annotations

import logging
import re
import threading
from contextlib import contextmanager
from typing import Any, Iterator

log = logging.getLogger("plantguard.pg")

_PLACEHOLDER = re.compile(r"\?")


def to_pg(sql: str) -> str:
    """SQLite-style SQL -> psycopg SQL: `?` -> `%s` (outside quotes), literal `%` -> `%%`."""
    out, quote = [], None
    for ch in sql:
        if quote:
            out.append("%%" if ch == "%" else ch)
            if ch == quote:
                quote = None
            continue
        if ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%":
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


class Row(dict):
    """dict access by column name plus positional access, like sqlite3.Row."""

    __slots__ = ("_vals",)

    def __init__(self, cols, vals):
        super().__init__(zip(cols, vals))
        self._vals = vals

    def __getitem__(self, k):
        if isinstance(k, int):
            return self._vals[k]
        return dict.__getitem__(self, k)


def _row_factory(cursor):
    cols = [c.name for c in (cursor.description or [])]
    return lambda values: Row(cols, values)


# ---------------------------------------------------------------- schema translation
_CREATE = re.compile(r"CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\((.*?)\);", re.S | re.I)
_INDEX = re.compile(r"CREATE (?:UNIQUE )?INDEX IF NOT EXISTS[^;]+;", re.I)
_REFS = re.compile(r"REFERENCES\s+(\w+)", re.I)


def translate_schema(schema: str) -> list[str]:
    """The shared (SQLite-flavoured) DDL -> Postgres statements, tables in foreign-key order, then indexes."""
    tables: dict[str, str] = {}
    deps: dict[str, set[str]] = {}
    for name, body in _CREATE.findall(schema):
        body = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                      body, flags=re.I)
        body = re.sub(r"\bid INTEGER PRIMARY KEY\b", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", body,
                      flags=re.I)
        body = re.sub(r"\bREAL\b", "DOUBLE PRECISION", body)
        tables[name] = f"CREATE TABLE IF NOT EXISTS {name} ({body});"
        deps[name] = {r for r in _REFS.findall(body) if r != name}
    ordered, done = [], set()

    def visit(n: str, path: tuple = ()):
        if n in done or n not in tables:
            return
        if n in path:
            raise ValueError(f"foreign-key cycle: {' -> '.join(path + (n,))}")
        for d in sorted(deps[n]):
            visit(d, path + (n,))
        done.add(n)
        ordered.append(tables[n])

    for n in tables:
        visit(n)
    return ordered + _INDEX.findall(schema)


class PgDatabase:
    """One PostgreSQL database (OT or IT) behind a small connection pool."""

    dialect = "postgres"

    def __init__(self, dsn: str, schema: str, name: str = "db", min_size: int = 1, max_size: int = 10,
                 migrations: list[str] | None = None):
        import psycopg
        from psycopg.types.numeric import FloatLoader
        from psycopg_pool import ConnectionPool

        self.name, self.dsn = name, dsn
        self.path = name  # parity with the SQLite store (logs, health checks)

        def configure(conn):
            conn.adapters.register_loader("numeric", FloatLoader)  # AVG/SUM come back as float, like SQLite
            conn.autocommit = True

        self._pool = ConnectionPool(dsn, min_size=min_size, max_size=max_size, kwargs={"row_factory": _row_factory},
                                    configure=configure, open=True, name=f"plantguard-{name}", timeout=30)
        self._local = threading.local()  # the connection of an open transaction (per thread)
        import atexit
        atexit.register(self._pool.close)
        self._psycopg = psycopg
        with self._pool.connection() as conn:
            # one process at a time creates/migrates the schema (several services may start together)
            conn.execute("SELECT pg_advisory_lock(hashtext(%s))", (f"plantguard-schema-{name}",))
            try:
                for stmt in translate_schema(schema):
                    conn.execute(stmt)
                for stmt in migrations or []:
                    conn.execute(stmt)
            finally:
                conn.execute("SELECT pg_advisory_unlock(hashtext(%s))", (f"plantguard-schema-{name}",))

    # ---- plumbing ----
    @contextmanager
    def _conn(self):
        tx = getattr(self._local, "conn", None)
        if tx is not None:  # inside tx(): stay on its connection
            yield tx
            return
        with self._pool.connection() as conn:
            yield conn

    # ---- queries (same signatures as the SQLite store) ----
    def q(self, sql: str, args: tuple | list = ()) -> list[Row]:
        with self._conn() as c:
            return c.execute(to_pg(sql), tuple(args)).fetchall()

    def one(self, sql: str, args: tuple | list = ()) -> Row | None:
        with self._conn() as c:
            return c.execute(to_pg(sql), tuple(args)).fetchone()

    def val(self, sql: str, args: tuple | list = (), default: Any = None) -> Any:
        row = self.one(sql, args)
        return row[0] if row is not None and row[0] is not None else default

    def x(self, sql: str, args: tuple | list = ()) -> int:
        with self._conn() as c:
            return c.execute(to_pg(sql), tuple(args)).rowcount

    def xc(self, sql: str, args: tuple | list = ()) -> int:
        """Execute one statement; returns the number of rows changed."""
        return self.x(sql, args)

    def insert_id(self, sql: str, args: tuple | list = ()) -> int:
        """INSERT and return the generated `id` column."""
        with self._conn() as c:
            return c.execute(to_pg(sql) + " RETURNING id", tuple(args)).fetchone()[0]

    def many(self, sql: str, rows: list[tuple]) -> None:
        if not rows:
            return
        with self._conn() as c:
            with c.cursor() as cur:
                cur.executemany(to_pg(sql), rows)

    @contextmanager
    def tx(self) -> Iterator["_TxConn"]:
        """A transaction on one connection: commits together or not at all. Nested calls join the outer one."""
        if getattr(self._local, "conn", None) is not None:
            yield _TxConn(self._local.conn)
            return
        with self._pool.connection() as conn:
            self._local.conn = conn
            try:
                with conn.transaction():
                    yield _TxConn(conn)
            finally:
                self._local.conn = None

    def advisory_lock(self, conn: "_TxConn", key: str) -> None:
        """Serialise a critical section across every process (released at the end of the transaction)."""
        conn.execute("SELECT pg_advisory_xact_lock(hashtext(?))", (key,))

    @contextmanager
    def session_lock(self, key: str, timeout_s: float = 600):
        """Hold a cross-process lock for a longer job (seeding, index builds) on a dedicated connection, so the job
        itself can keep using the pool normally."""
        import time
        with self._pool.connection() as conn:
            deadline = time.monotonic() + timeout_s
            while not conn.execute("SELECT pg_try_advisory_lock(hashtext(%s))", (key,)).fetchone()[0]:
                if time.monotonic() > deadline:
                    raise TimeoutError(f"lock {key} not released within {timeout_s:.0f} s")
                time.sleep(0.5)
            try:
                yield
            finally:
                conn.execute("SELECT pg_advisory_unlock(hashtext(%s))", (key,))

    # ---- key/value + id sequences ----
    def meta(self, key: str, default: str | None = None) -> str | None:
        row = self.one("SELECT value FROM meta WHERE key=?", (key,))
        return row["value"] if row else default

    def set_meta(self, key: str, value: str) -> None:
        self.x("INSERT INTO meta(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
               (key, value))

    def next_id(self, name: str, start: int) -> int:
        """Atomic across every process and instance."""
        return int(self.val("INSERT INTO id_sequences(name, next) VALUES(?, ?) ON CONFLICT(name) DO UPDATE "
                            "SET next=id_sequences.next + 1 RETURNING next - 1", (name, start + 1)))

    def ping(self) -> bool:
        return self.val("SELECT 1") == 1

    def close(self) -> None:
        self._pool.close()

    def wipe(self) -> None:
        """Drop every table (SIM_RESET in a dev/test database only)."""
        with self._conn() as c:
            tables = [r[0] for r in c.execute("SELECT tablename FROM pg_tables WHERE schemaname='public'").fetchall()]
            if tables:
                c.execute("DROP TABLE IF EXISTS " + ", ".join(tables) + " CASCADE")


class _TxConn:
    """What `with db.tx() as c` yields: c.execute(sql, args) with SQLite-style SQL, returning a cursor."""

    def __init__(self, conn):
        self._c = conn

    def execute(self, sql: str, args: tuple | list = ()):
        return self._c.execute(to_pg(sql), tuple(args))

    def executemany(self, sql: str, rows: list[tuple]):
        with self._c.cursor() as cur:
            cur.executemany(to_pg(sql), rows)
